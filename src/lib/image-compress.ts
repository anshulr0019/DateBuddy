/**
 * Client-side high-fidelity image compressor.
 * Downscales ultra-large camera raw files (e.g. 48MP iPhone / DSLR shots)
 * down to crisp 1600px max dimensions and ~800KB size before sending to /api/upload.
 * Eliminates upload timeouts, 413 errors, and mobile data lag.
 */
export async function compressImageForUpload(file: File, maxDimension = 1800, quality = 0.85): Promise<File> {
  // If already under 1.2MB and a standard format, upload directly
  if (file.size <= 1.2 * 1024 * 1024 && !file.type.includes('heic')) {
    return file;
  }

  return new Promise((resolve) => {
    const reader = new FileReader();
    reader.readAsDataURL(file);
    reader.onload = (event) => {
      const img = new Image();
      img.src = event.target?.result as string;
      img.onload = () => {
        let width = img.width;
        let height = img.height;

        if (width > maxDimension || height > maxDimension) {
          if (width > height) {
            height = Math.round((height * maxDimension) / width);
            width = maxDimension;
          } else {
            width = Math.round((width * maxDimension) / height);
            height = maxDimension;
          }
        }

        const canvas = document.createElement('canvas');
        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext('2d');
        if (!ctx) {
          resolve(file);
          return;
        }

        ctx.drawImage(img, 0, 0, width, height);

        canvas.toBlob(
          (blob) => {
            if (!blob) {
              resolve(file);
              return;
            }
            const compressedFile = new File([blob], file.name.replace(/\.[^/.]+$/, '.jpg'), {
              type: 'image/jpeg',
              lastModified: Date.now(),
            });
            resolve(compressedFile);
          },
          'image/jpeg',
          quality
        );
      };
      img.onerror = () => resolve(file);
    };
    reader.onerror = () => resolve(file);
  });
}
