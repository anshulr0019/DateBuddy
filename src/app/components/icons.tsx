export function WhatsAppTicks({
  status,
  isMine = true,
  className = "",
}: {
  status: 'sent' | 'delivered' | 'seen';
  isMine?: boolean;
  className?: string;
}) {
  if (status === 'sent') {
    return (
      <WhatsAppSingleTick
        className={`w-3.5 h-3.5 text-gray-400 ${className}`}
      />
    );
  }

  if (status === 'delivered') {
    return (
      <WhatsAppDoubleTick
        className={`w-4 h-3.5 text-gray-400 ${className}`}
      />
    );
  }

  // status === 'seen' -> Soft decent rose pink double tick!
  return (
    <WhatsAppDoubleTick
      className={`w-4 h-3.5 text-[#F43F5E] ${className}`}
    />
  );
}


